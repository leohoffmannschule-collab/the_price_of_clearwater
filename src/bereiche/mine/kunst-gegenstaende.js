      E(g, 11, 5, 3.6, 3.6, b.f); E(g, 10, 4, 1.8, 1.6, hell(b.f, 0.35)); E(g, 12, 6.5, 1.6, 1.2, dunkel(b.f, 0.2));
      for (const [x, y] of [[13, 2], [14, 6], [9, 2]]) P(g, x, y, b.f3);
